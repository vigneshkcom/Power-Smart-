-- PowerSmart field jobs: electricians + scheduled jobs.
-- Run once in Supabase → SQL Editor (after schema.sql).
-- RLS enabled with no policies → only the serverless functions (service_role) can access.

create extension if not exists pgcrypto;

-- ---------- Electricians (fieldworkers) ----------
create table if not exists public.electricians (
  id          uuid primary key default gen_random_uuid(),
  created_at  timestamptz not null default now(),
  code        text,                         -- short ID shown on the board, e.g. 1011
  name        text not null,
  phone       text,
  email       text,
  active      boolean not null default true,
  sort_order  int not null default 0
);

-- ---------- Jobs ----------
create table if not exists public.jobs (
  id               uuid primary key default gen_random_uuid(),
  job_no           bigint generated by default as identity (start with 1001) unique,  -- shown as J1001
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now(),
  lead_id          uuid references public.leads(id) on delete set null,
  quote_ref        text,                    -- quote selected when the job was created
  electrician_id   uuid references public.electricians(id) on delete set null,
  scheduled_start  timestamptz,               -- null = waiting list
  duration_min     int not null default 60 check (duration_min between 15 and 720),
  status           text not null default 'scheduled'
                   check (status in ('scheduled','en_route','on_site','completed','cancelled')),
  work_type        text not null default 'install'
                   check (work_type in ('install','inspection','service')),
  customer_name    text not null,
  phone            text,
  email            text,
  address          text,
  suburb           text,
  postcode         text,
  alarms           int,
  notes            text,
  created_by       text
);

create index if not exists jobs_start_idx  on public.jobs (scheduled_start);
create index if not exists jobs_tech_idx   on public.jobs (electrician_id);
create index if not exists jobs_status_idx on public.jobs (status);
create index if not exists jobs_lead_idx   on public.jobs (lead_id);

-- keep updated_at fresh (same helper as schema.sql)
create or replace function public.touch_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end $$;

drop trigger if exists jobs_touch on public.jobs;
create trigger jobs_touch before update on public.jobs
  for each row execute function public.touch_updated_at();

alter table public.electricians enable row level security;
alter table public.jobs         enable row level security;
